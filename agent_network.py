from collections import defaultdict


# ==========================================
# 1. Hypergraph Attribute Feature Pooling
# ==========================================

def get_feature_pools(agents):
    """
    Place agents into candidate pools based on all attributes (occupation + all interests).
    Read directly, no longer randomly generated, ensuring absolute decoupling from the data source.
    """
    pools = defaultdict(list)

    for uid, data in agents.items():
        uid_int = int(uid)
        occ = data['demographics']['occupation']

        # 1. Add to occupation pool
        pools[f"occ_{occ.lower().replace(' ', '_')}"].append(uid_int)

        # 2. Add to multiple interest pools (depends on interests generated by program 1)
        for inter in data.get('interests', []):
            pools[f"interest_{inter.lower()}"].append(uid_int)

    # Filter out pools with less than 2 people (cannot form social edges)
    valid_pools = {k: v for k, v in pools.items() if len(v) >= 2}
    return valid_pools


# ==========================================
# 2. Core Network Generation (Network Engine)
# ==========================================

def build_network(agents, args):
    n = len(agents)
    seed = args.seed
    avg_deg = args.avg_degree

    random.seed(seed)
    np.random.seed(seed)

    # --- Network Parameter Calculation ---
    p_er = avg_deg / (n - 1)
    m_ba = max(1, int(avg_deg / 2))
    k_ws = int(avg_deg)
    p_ws = 0.1
    # Cast to integer to avoid numpy errors
    target_edges = int((n * avg_deg) / 2)
    # -------------------

    if args.type == 'er':
        G = nx.erdos_renyi_graph(n, p_er, seed=seed)
    elif args.type == 'ba':
        G = nx.barabasi_albert_graph(n, m_ba, seed=seed)
    elif args.type == 'ws':
        G = nx.watts_strogatz_graph(n, k_ws, p_ws, seed=seed)
    elif args.type == 'hyper':
        G = generate_controlled_hypergraph(agents, target_edges, seed)

        # [Ultimate Fix: Bridge all islands to ensure 100% network connectivity]
        if not nx.is_connected(G):
            # Find all disconnected components (sorted by size descending)
            components = sorted(nx.connected_components(G), key=len, reverse=True)
            largest_cc = set(components[0])  # Main continent

            # Iterate through all overseas islands
            for island in components[1:]:
                # Randomly select a person from the island
                node_in_island = random.choice(list(island))
                # Randomly select a person from the main continent
                node_in_main = random.choice(list(largest_cc))
                # Build a bridge across the sea!
                G.add_edge(node_in_island, node_in_main, weight=1)
                # Merge this island's population into the main continent, so subsequent islands can connect to them
                largest_cc.update(island)

            print(f"  --> Bridged {len(components) - 1} islands, the network is now 100% connected!")

    return G


def generate_controlled_hypergraph(agents, target_edges, seed):
    """
    Controlled hypergraph projection:
    Limit group sizes to 3~5 people, and allow individuals to exist across multiple circles.
    """
    G = nx.Graph()
    G.add_nodes_from([int(i) for i in agents.keys()])

    valid_pools = get_feature_pools(agents)
    if not valid_pools:
        print("Warning: Not enough data found to establish hyperedges!")
        return G

    pool_keys = list(valid_pools.keys())

    attempts = 0
    while G.number_of_edges() < target_edges and attempts < 10000:
        attempts += 1

        # 1. Randomly pick an attribute group
        chosen_feature = random.choice(pool_keys)
        pool_members = valid_pools[chosen_feature]

        # 2. Determine the size of this hyperedge (3 to 5 people is optimal)
        max_possible = min(len(pool_members), 5)
        if max_possible < 2:
            continue
        min_size = 3 if max_possible >= 3 else 2
        he_size = random.randint(min_size, max_possible)

        # 3. Draw people to form a group
        he_members = random.sample(pool_members, he_size)

        # 4. Connect people within the circle (equal weight)
        for i in range(len(he_members)):
            for j in range(i + 1, len(he_members)):
                u, v = he_members[i], he_members[j]
                if not G.has_edge(u, v):
                    G.add_edge(u, v, weight=1)

    return G


# ==========================================
# 3. Metrics Statistics and Output (Stats)
# ==========================================

def analyze_and_save(agents, G, args):
    print("\n" + "=" * 45)
    print(f"  Network Analysis ({args.type.upper()})")
    print("=" * 45)

    nodes = G.number_of_nodes()
    edges = G.number_of_edges()
    projected_avg_degree = sum(dict(G.degree()).values()) / nodes

    # [New] Calculate the true "number of hyperedges belonged to" for hypergraphs
    hypergraph_avg_degree = None
    if args.type == 'hyper':
        total_hyper_degrees = 0
        for data in agents.values():
            # True hyper-degree = 1 occupation + N interests
            hyper_degree = 1 + len(data.get('interests', []))
            total_hyper_degrees += hyper_degree
        hypergraph_avg_degree = total_hyper_degrees / nodes

    # Calculate diameter and path length
    if nx.is_connected(G):
        diameter = nx.diameter(G)
        aspl = nx.average_shortest_path_length(G)
    else:
        largest_cc = max(nx.connected_components(G), key=len)
        subgraph = G.subgraph(largest_cc)
        diameter = nx.diameter(subgraph)
        aspl = nx.average_shortest_path_length(subgraph)
        print(f"  [Warning] Graph not fully connected. Stats based on Largest CC ({len(largest_cc)} nodes).")

    print(f"  1. Node Count:        {nodes}")
    print(f"  2. Edge Count:        {edges}")

    # Report two types of degrees separately to highlight academic rigor
    if args.type == 'hyper':
        print(f"  3a. Hyper Avg Degree: {hypergraph_avg_degree:.2f} (Number of communities/hyperedges belonged to)")
        print(f"  3b. Proj. Avg Degree: {projected_avg_degree:.2f} (Actual number of social neighbors)")
    else:
        print(f"  3.  Avg Degree:       {projected_avg_degree:.2f}")

    print(f"  4. Network Diameter:  {diameter}")
    print(f"  5. Avg Shortest Path: {aspl:.4f}")
    print("=" * 45 + "\n")

    # Serialize and save
    for u in G.nodes():
        neighbors = [{"id": str(v), "w": G[u][v].get('weight', 1)} for v in G.neighbors(u)]
        agents[str(u)]["neighbors"] = neighbors

    output_data = {
        "metrics": {"nodes": nodes, "edges": edges, "avg_degree": projected_avg_degree, "diameter": diameter,
                    "aspl": aspl},
        "agents": agents
    }

    with open(args.output, 'w', encoding='utf-8') as f:
        json.dump(output_data, f, indent=2)


